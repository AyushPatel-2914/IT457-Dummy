"""Combine every run's summary.json into one table and the comparison charts for the report.

Groups runs by results/<stage>/<experiment>/run*/ and reports the median and range over runs.
Outputs:
    results/summary_table.md
    results/charts/availability_by_experiment.png
    results/charts/recovery_by_experiment.png
    results/charts/latency_vs_load.png         (from E5 ramp runs)
    results/charts/latency_vs_instances.png    (from E5 runs that have watch.csv, i.e. AWS S2)
"""
import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "results"
CHARTS = RESULTS / "charts"


def load_summaries():
    rows = []
    for f in sorted(RESULTS.glob("*/*/run*/summary.json")):
        s = json.loads(f.read_text())
        stage, exp = f.parts[-4], f.parts[-3]
        if "check" in exp:  # smoke-test runs
            continue
        rows.append({"stage": stage, "experiment": exp, "group": f"{stage} {exp}", "run": f.parts[-2], **{
            k: s.get(k) for k in ["availability_pct", "home_p50_ms", "home_p95_ms", "home_p99_ms", "throughput_rps",
                                  "error_rate_all_pct", "degraded_seconds", "outage_seconds", "longest_outage_s",
                                  "mean_time_to_recover_s", "unrecovered_events", "mean_time_to_restore_capacity_s",
                                  "fallback_pct_of_home", "slo_met"]}})
    return pd.DataFrame(rows)


def fmt(series, digits=1):
    s = series.dropna()
    if s.empty:
        return "-"
    med = f"{s.median():.{digits}f}"
    return med if len(s) == 1 or s.min() == s.max() else f"{med} ({s.min():.{digits}f}-{s.max():.{digits}f})"


def table(df):
    lines = ["# Results summary", "",
             "Generated by `loadtest/compare.py`. Values are the median over runs, with the range in brackets. "
             "Availability = share of home-page requests answered with HTTP 200 within 1 s.", "",
             "| Stage | Experiment | Runs | Availability % | SLO 99% met | p50 ms | p95 ms | Throughput req/s | "
             "Longest outage s | Time to recover s | Capacity restored s | Home pages on fallback % |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for (stage, exp), g in df.groupby(["stage", "experiment"], sort=False):
        lines.append(f"| {stage} | {exp} | {len(g)} | {fmt(g.availability_pct, 2)} | "
                     f"{int(g.slo_met.sum())}/{len(g)} | {fmt(g.home_p50_ms)} | {fmt(g.home_p95_ms)} | "
                     f"{fmt(g.throughput_rps)} | {fmt(g.longest_outage_s, 0)} | {fmt(g.mean_time_to_recover_s)} | "
                     f"{fmt(g.mean_time_to_restore_capacity_s)} | {fmt(g.fallback_pct_of_home)} |")
    (RESULTS / "summary_table.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


def bar(df, cols, labels, ylabel, title, path, ylim=None):
    agg = df.groupby("group", sort=False)[cols].agg(["median", "min", "max"])
    fig, ax = plt.subplots(figsize=(max(6, 1.1 * len(agg)), 3.8))
    width = 0.8 / len(cols)
    colours = ["#2a6", "#36c", "#c80"]
    for i, col in enumerate(cols):
        med = agg[(col, "median")]
        err = [med - agg[(col, "min")], agg[(col, "max")] - med]
        x = [j + i * width for j in range(len(agg))]
        ax.bar(x, med.fillna(0), width, yerr=err, capsize=3, label=labels[i], color=colours[i])
    ax.set_xticks([j + width * (len(cols) - 1) / 2 for j in range(len(agg))])
    ax.set_xticklabels(agg.index, rotation=25, ha="right", fontsize=8)
    ax.set_ylabel(ylabel)
    ax.set_title(title, fontsize=10)
    if ylim:
        ax.set_ylim(*ylim)
    if len(cols) > 1:
        ax.legend(fontsize=8)
    ax.grid(axis="y", alpha=0.3)
    fig.tight_layout()
    fig.savefig(path, dpi=130)
    plt.close(fig)


def windows(run_dir, size=30):
    req = pd.read_csv(run_dir / "requests.csv")
    t0 = req["ts_start"].min()
    req["w"] = ((req["ts_start"] - t0) // size) * size
    home = req[(req["name"] == "home") & (req["status"] == 200)]
    out = pd.DataFrame({"rps": req.groupby("w").size() / size,
                        "p95": home.groupby("w")["latency_ms"].quantile(0.95),
                        "p50": home.groupby("w")["latency_ms"].quantile(0.5)})
    if (run_dir / "watch.csv").exists():
        w = pd.read_csv(run_dir / "watch.csv")
        col = "tg_healthy" if "tg_healthy" in w and w["tg_healthy"].notna().any() else "ec2_running"
        w["w"] = ((w["ts"] - t0) // size) * size
        out["instances"] = w.groupby("w")[col].median()
    return out.dropna(subset=["p95"])


def scaling_charts():
    runs = sorted(RESULTS.glob("*/e5/run*/requests.csv"))
    if not runs:
        return
    fig, ax = plt.subplots(figsize=(7, 4))
    for f in runs:
        w = windows(f.parent)
        ax.plot(w["rps"], w["p95"], marker="o", ms=3, label=f"{f.parts[-4]} {f.parts[-2]}")
    ax.set_xlabel("throughput (requests/s, 30 s window)")
    ax.set_ylabel("home p95 latency (ms)")
    ax.set_title("E5 ramp: latency vs load", fontsize=10)
    ax.grid(alpha=0.3)
    ax.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(CHARTS / "latency_vs_load.png", dpi=130)
    plt.close(fig)

    with_instances = [f for f in runs if (f.parent / "watch.csv").exists()]
    if not with_instances:
        return
    frames = pd.concat([windows(f.parent) for f in with_instances]).dropna(subset=["instances"])
    g = frames.groupby(frames["instances"].round())[["p50", "p95", "rps"]].median()
    fig, ax = plt.subplots(figsize=(6, 4))
    ax.plot(g.index, g["p95"], marker="o", label="p95", color="#c80")
    ax.plot(g.index, g["p50"], marker="o", label="p50", color="#36c")
    for n, row in g.iterrows():
        ax.annotate(f"{row.rps:.0f} req/s", (n, row.p95), fontsize=7, xytext=(4, 4), textcoords="offset points")
    ax.set_xlabel("healthy instances")
    ax.set_ylabel("home latency (ms)")
    ax.set_title("S2: response time vs instance count (E5)", fontsize=10)
    ax.grid(alpha=0.3)
    ax.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(CHARTS / "latency_vs_instances.png", dpi=130)
    plt.close(fig)


def main():
    CHARTS.mkdir(parents=True, exist_ok=True)
    df = load_summaries()
    if df.empty:
        raise SystemExit("no summary.json files under results/")
    table(df)
    bar(df, ["availability_pct"], ["availability"], "availability %", "Home-page availability by experiment",
        CHARTS / "availability_by_experiment.png", ylim=(min(90, df.availability_pct.min() - 2), 100.5))
    chaos = df[df["mean_time_to_recover_s"].notna() | df["mean_time_to_restore_capacity_s"].notna()]
    if not chaos.empty:
        bar(chaos, ["mean_time_to_recover_s", "mean_time_to_restore_capacity_s"],
            ["customer recovery", "capacity restored"], "seconds", "Recovery time after a chaos event",
            CHARTS / "recovery_by_experiment.png")
    bar(df, ["home_p50_ms", "home_p95_ms"], ["p50", "p95"], "ms", "Home-page latency by experiment",
        CHARTS / "latency_by_experiment.png")
    scaling_charts()


if __name__ == "__main__":
    main()
